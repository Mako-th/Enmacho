using System.Globalization;

namespace TH09.Shell.Data;

internal static class StatsDefinitions
{
    public const string HistoryTail =
        "。戻れるのは階層（区分とパス）だけで、キャラのチェック・「他人のリプレイも含める」・"
        + "「全組み合わせ表」は履歴に積んでいない（あれは階層ではなく見え方の設定なので）。"
        + "★行き先は「区分 ＋ パス」を丸ごと控えている——差分ではないので、区分を跨いでも戻れる";

    public const string ExtraSourceNote =
        "★「最高最終スコア」「終了スコアの最高」「ラウンド最長時間」の 3 枚には出典を付けてある"
        + "（この画面だけのもので、今の統計 HTML には無い）。出典はカードの数字を出した走り"
        + "そのもので、実プレイ #セッション / スキャン #セッション（Replay #リプレイ）の 2 種類。"
