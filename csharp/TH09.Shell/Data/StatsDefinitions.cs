    public static List<string> All(StatsPayload p, string historyNote)
    {
        var notes = new List<string>();

        var one = "自分の名前は DB から採った（定数で持っていない）: " + (p.MyName ?? "不明");
        one += p.OwnNames.Count > 0
            ? "  ＝ " + string.Join(" / ", p.OwnNames.Select(
                  x => x.Name + " " + x.Count.ToString("N0", CultureInfo.InvariantCulture)))
              + "（replays の is_own=1 で側が分かる行の、自分側の名前を数えた。"
              + "表記ゆれは畳まずそのまま突き合わせに使う）"
            : "（replays に名前が無い）";
        if (p.DroppedNames.Count > 0)
            one += "  ★相手側にも同じ表記が出るので使わなかった: "
                   + string.Join(" / ", p.DroppedNames.Select(
                         x => x.Name + " " + x.Count.ToString("N0", CultureInfo.InvariantCulture)));
        notes.Add(one);

        notes.Add("名前で自分側を決めた件数と、replays.owner_side と食い違った件数は上の"
            + "行。食い違いが 0 でないなら、名前の一覧か owner_side のどちらかが疑わしい");

        notes.Add("自分がどちら側か決められないセッションは集計から外し、件数を上に出している。★推測で埋め"
            + "ない——決まらないものは外して件数だけ出す");

        notes.Add("★仮と付いた記録は、ネット対戦の実プレイでリプレイ（＝自動保存フォルダ A vs B）が"
            + "無く、自分側が確定できないもの。1P と置いて集計に入れてあるが、要約カードと葉の表に件"
            + "数と印を出している。adonis2 のメモリから読めるのは「ローカル / リモートの名前"
            + "」だけで、1P / 2P は自動保存パスでしか決まらない");

        notes.Add("母数 n は隠していない。n=1 でも行として出る");

        notes.Add("表の真上の帯には、いま絞り込みで 1 つに決まっている値だけを出す（自キャラ・難易度・面"
            + "など）。行ごとに変わる軸は出さない——それは表の左端の列に出ている。全組み合わせ表から絞"
            + "って飛ばした段（「すべて」）も出さない（決まっていないので）。パンくずと同じ値を出してい"
            + "るが、作っているのは 1 か所（PathLabels）");

        notes.Add("★" + historyNote + HistoryTail);

        notes.Add("プレイの最終スコアは、そのセッションの stages.score_at_end の最大（"
            + "定義は th09_repository.final_score_bests と同じ）。面"
            + "ごとのスコアの合計とは別物——途中の面から記録が始まっているプレイでは食い違う");

        notes.Add("面まで降りた画面は表を 2 枚に分けている。上＝終了スコア"
            + "（そのラウンドを終えた時点の通しスコア。自己ベストは終了スコアで決まるので同じ土俵で比べ"
            + "る）と時間、下＝区間スコア（＝画面の見出しの「その面で稼いだスコア」。呼び名は自己ベスト"
            + "タブの列名に揃えてある）。どちらもラウンドごとに割ってある。★Story/Extra も"
            + "面を落とすとやり直しなので、その面は R2・R3 の行が出る（負けた回＝ミスの多さがここ"
            + "に出る）。★割り方（テレスコープ分割）: ラウンドの終了スコア＝次のラウンドの roun"
            + "ds.score_1_at_start（面の最後のラウンドだけ stages.score"
            + "_at_end）、区間スコア＝それ − そのラウンド自身の score_1_at_sta"
            + "rt。面の全ラウンドの区間を足すと面の増分にぴたりと一致する（実測 2026-08-09"
            + ": 一致しない面は 0 / 810）。★rounds.score_1_at_end は使"
            + "っていない——あれは「勝負がついた tick」の値で、その後もアイテム回収等で点が入るた"
            + "め合計が面と一致しない（非最終ラウンド 211/211 で隙間があり中央値 861,67"
            + "0）。最短時間だけは自己ベストと同じ下限ガード "
            + StatsLeafQuery.MinStageFrames.ToString(CultureInfo.InvariantCulture)
            + "f を掛けている（平均・最高・最低・最長はガード無しの全件）");

        notes.Add("★クリアボーナス（ゲーム内表示「貴方の付加価値」）は引き算で求めていない——clear_"
            + "bonuses.total_bonus をそのまま出している（stages.clear_"
            + "bonus_id で紐付く。実測 2026-08-09: Story/Extra 811"
            + " 面のうち810 面に紐付き、欠けるのは進行中の 1 面だけ）。面をクリアしたラウンド＝"
            + "最後のラウンドの行にだけ載るので、この列の n は他の列の n より小さい（各セルの吹き"
            + "出しに n を出している）。★ボーナスの 2 列は上の表（終了スコア）にも同じ形で出して"
            + "いる。★列名は「"
            + "終了スコア（CB除く）」「区間（CB除く）」と表ごとに言い分けている【2026-08-0"
            + "9 に直した。単に「ボーナス除く」だけだった時期があり、上の表と下の表で同じ名前が違う値"
            + "（終了スコア − ボーナス / 区間スコア − ボーナス）を指していた】。どちらもその表"
            + "の主の列 − そのラウンドのクリアボーナス（上の表なら終了スコアから、下の表なら区間スコ"
            + "アから引く）で、ボーナスの無いラウンドは主の列そのもの——だから「（ボーナス除く）」＋「"
            + "うちクリアボーナス」＝ 主の列がどちらの表でも常に閉じる。★上の表で引くのもその面のボー"
            + "ナスだけで、それまでの面のボーナスの累計は引いていない"
            + "——2 つの表の「うちクリアボーナス」が別の数を指さないようにするため。★clear_b"
            + "onuses.score_before_bonus / score_after_bonu"
            + "s は使っていない（実測 810/810 で after == before + tot"
            + "al ＝ 計算値であり、独立した根拠にならない）");

        notes.Add("残機は「"
            + StatsAggColumns.LivesTip
            + "」。★制覇表（tools/gen_play_matrix.py）の「最高残機」とは定義は"
            + "同じだが母集団が違う——あちらは 9 面到達のプレイだけで比べている。この画面は母数を隠"
            + "さないので全プレイで出す。★Match には残機という概念が存在しないので、Match "
            + "の表には残機の 3 列そのものを出していない（実測で "
            + "stages.lives_at_end は 1,348/1,348 が 0.0）。「空白"
            + "が情報」＝やっていないことが分かるための原則なので、概念が無い列は対象外という理屈。St"
            + "ory/Extra と Match(対 CPU) を「同じ形」にする指定は生きていて、画"
            + "面の器は 1 つのまま列の有無だけを切り替えている");

        notes.Add("★Match(ローカル) は Match(ネット) と同じ階層・同じ表・同じカードで出す"
            + "。ローカル対人は対戦時にプレイヤー名が分からないので相手プ"
            + "レイヤーの段は「（名前なし）」1 つに束ねて出る。後から名前を埋める機能はまだ作っていない"
            + "が、埋めれば自然に割れるように段だけ先に用意し"
            + "てある");

        notes.Add("「自陣にボスが居た時間」は pN_boss_present_ticks＝「N の陣にボス"
            + "が居た時間」。「N がボスを送った」ではない");

        notes.Add("★葉（1 件ずつの表）に ラウンドごとの時間の列を足した"
            + "。合計は消していない——Match の「時間」は今ま"
            + "でどおりマッチ全体の合計で、その隣にラウンド 1 本ずつを並べている。Story/Ext"
            + "ra の葉は 1 行 = 1 ラウンドなので「時間」はそのラウンドの時間で、隣にはその面"
            + "の全ラウンド（やり直すと R2・R3… と増える）を出し、その行のラウンドを太字にしてい"
            + "る。★並べる順は round_number 順（記録された順ではない）。★時間の記録が無"
            + "いラウンドは「—」で、0 とは書かない——記録中のラウンドは duration_fram"
            + "es が NULL のままなので、0 と書くと「一瞬で終わった」に読める。中断・進行中の"
            + "ラウンドには（中断）（進行中）と付ける（実測 2026-08-09: 本体 DB 4,1"
            + "74 ラウンドのうち completed 4,170 / aborted 4）");

        notes.Add("要約カードの強い区切りは、表の ┃ と同じもの（描き方を 1 つに揃えてある・色は Bo"
            + "rder.cardgroup と Border.aggbar で同じ）。群の切り方は区分"
            + "によって違う: Match は回数・勝敗 ┃ 時間 ┃ スコア ┃ 参考、Story/E"
            + "xtra のプレイ単位はすぐ下の表と同じ 回数 ┃ 最高 ┃ 平均 ┃ 最低 ┃ 参考、"
            + "面まで降りた後は回数 ┃ 終了スコア ┃ 時間 ┃ 参考（合計）。★カードの並びは 1 "
            + "枚も動かしていない（元の並びの境目に区切りを入れただけ）");

        notes.Add(ExtraSourceNote);

        return notes;
    }
}
